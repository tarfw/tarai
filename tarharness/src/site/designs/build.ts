/**
 * The design library pipeline (parai §3.2) as one pure function: source files in,
 * shippable artifacts out. No fs and no AI, so `scripts/designdigest.ts` and the drift
 * test both run the same code path.
 *
 * Fatal errors are limited to a duplicate id, a missing default, or an empty library —
 * everything else about a single design becomes a review entry and that design is skipped.
 */

import { luminance } from '../contrast.ts';
import { COMMERCE_MODELS } from '../blueprint.ts';
import { TRADE_TAXONOMY } from '../../brain/trade.ts';
import { blocking, tagCheck, checkDesign, type CheckVocabulary } from './check.ts';
import {
  TOKENS_VERSION,
  type DesignIndex,
  type DesignIndexRow,
  type DesignReview,
  type DesignTags,
  type DesignTokens,
  type ParsedReference,
  type ReviewEntry,
  type ReviewFinding,
  type SidecarEntry,
} from './contract.ts';
import { parseDesignMd, paletteContrast, pickRole, resolveTokens } from './parse.ts';

export interface SourceFile {
  file: string;
  markdown: string;
  hash: string;
}

export interface LibraryBuild {
  index: DesignIndex;
  review: DesignReview;
  tokens: { id: string; text: string }[];
  library: string;
  /** Fatal build errors: the emitted artifacts must not be trusted when these exist. */
  errors: string[];
  /** Unsigned sources, with the observations a reviewer needs to fill in. */
  proposals: Record<string, SidecarEntry>;
}

const DENSITY_BY_SOURCE_WORD: Record<string, string> = {
  compact: 'compact',
  balanced: 'balanced',
  comfortable: 'airy',
  airy: 'airy',
  roomy: 'airy',
  tight: 'compact',
};

export const LIBRARY_VOCABULARY: CheckVocabulary = {
  industries: Object.keys(TRADE_TAXONOMY),
  models: [...COMMERCE_MODELS],
};

/** Two-space JSON with a trailing newline; key order comes from the objects we build. */
export function renderJson(value: unknown): string {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function indexRow(tags: DesignTags, tokens: DesignTokens): DesignIndexRow {
  return {
    id: tags.id,
    label: tags.label,
    desc: tags.desc,
    tone: tags.tone,
    density: tags.density,
    industries: [...new Set(tags.industries)].sort(),
    models: [...new Set(tags.models)].sort(),
    imagery: tags.imagery,
    contrast: paletteContrast(tokens.color),
    swatches: [...new Set([tokens.color.canvas, tokens.color.ink, tokens.color.accent, tokens.color.surface])],
  };
}

/** What a reviewer sees for a file with no signed sidecar entry. */
export function proposalFor(reference: ParsedReference): SidecarEntry {
  const canvas = pickRole(reference, 'canvas')?.value ?? '#ffffff';
  return {
    id: '',
    label: reference.brand || reference.file,
    desc: reference.vibe.slice(0, 160),
    tone: (luminance(canvas) ?? 1) < 0.4 ? 'dark' : 'light',
    density: (DENSITY_BY_SOURCE_WORD[reference.densityWord ?? ''] as SidecarEntry['density']) ?? 'balanced',
    industries: ['general'],
    models: ['products'],
    imagery: 'editorial',
    direction: { audience: '', purpose: '', voice: '', idea: '' },
    guidance: [],
    license: { kind: 'reference', note: 'not recorded', approved: false },
    reviewer: '',
  };
}

function sortByName<T extends { file: string }>(entries: T[]): T[] {
  return [...entries].sort((a, b) => (a.file < b.file ? -1 : a.file > b.file ? 1 : 0));
}

function sortById<T extends { id: string }>(entries: T[]): T[] {
  return [...entries].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
}

/**
 * Pick the shipped default: the preferred id when it passed review, otherwise the first
 * id in alphabetical order, so the choice never depends on a brand name or file order.
 */
function chooseDefault(rows: DesignIndexRow[], preferred: string): string {
  if (rows.some((row) => row.id === preferred)) return preferred;
  return sortById(rows)[0]?.id ?? '';
}

export const PREFERRED_DEFAULT = 'luxury';

export function renderLibrary(index: DesignIndex, tokens: DesignTokens[]): string {
  const ordered = sortById(tokens);
  const imports = ordered
    .map((entry) => `import ${entry.id} from './tokens/${entry.id}.json';`)
    .join('\n');
  const map = ordered.map((entry) => `  ${entry.id}: ${entry.id} as unknown as DesignTokens,`).join('\n');
  return `/**
 * Generated by \`npm run designs\` from designmds/*.md. Do not edit.
 * Sources, tags and findings live in index.json, tokens/ and review.json.
 */

import type { DesignIndex, DesignTokens } from './contract.ts';
import indexJson from './index.json';
${imports}

export const GENERATED_INDEX: DesignIndex = indexJson as unknown as DesignIndex;

export const GENERATED_TOKENS: Record<string, DesignTokens> = {
${map}
};

export const GENERATED_DEFAULT = ${JSON.stringify(index.default)};

export const GENERATED_VERSION = ${index.version};
`;
}

export function buildLibrary(
  sources: SourceFile[],
  sidecar: Record<string, SidecarEntry>,
  vocab: CheckVocabulary = LIBRARY_VOCABULARY,
  preferredDefault = PREFERRED_DEFAULT,
): LibraryBuild {
  const errors: string[] = [];
  const proposals: Record<string, SidecarEntry> = {};
  const excluded: ReviewEntry[] = [];
  const notes: ReviewEntry[] = [];
  const shipped: { tokens: DesignTokens; row: DesignIndexRow }[] = [];
  const byId = new Map<string, string>();

  for (const source of [...sources].sort((a, b) => (a.file < b.file ? -1 : a.file > b.file ? 1 : 0))) {
    const reference = parseDesignMd(source.markdown, source.file);
    const entry = sidecar[source.file];
    if (!entry) {
      proposals[source.file] = proposalFor(reference);
      excluded.push({
        file: source.file,
        brand: reference.brand || undefined,
        findings: [{ check: 'tags', level: 'blocking', message: `${source.file} has no entry in scripts/designtags.json.` }],
      });
      continue;
    }

    const id = entry.id ?? '';
    const previous = byId.get(id);
    if (previous) {
      errors.push(`Duplicate design id "${id}": ${previous} and ${source.file}`);
      continue;
    }
    byId.set(id, source.file);

    const tagFindings = tagCheck(entry, source.file, vocab);
    if (blocking(tagFindings).length) {
      excluded.push({ file: source.file, id: id || undefined, brand: reference.brand || undefined, findings: tagFindings });
      continue;
    }

    const tags = entry as DesignTags;
    const tokens = resolveTokens(reference, tags, { file: source.file, hash: source.hash });
    const findings = checkDesign(reference, tokens);
    if (blocking(findings).length) {
      excluded.push({ file: source.file, id: tags.id, brand: reference.brand, findings });
      continue;
    }
    const advisory = findings.filter((finding: ReviewFinding) => finding.level === 'advisory');
    shipped.push({ tokens, row: indexRow(tags, tokens) });
    if (advisory.length || tokens.notes.length) {
      notes.push({
        file: source.file,
        id: tags.id,
        brand: reference.brand,
        findings: [
          ...advisory,
          ...tokens.notes.map((note) => ({ check: 'derived', level: 'advisory' as const, message: note })),
        ],
      });
    }
  }

  const rows = sortById(shipped.map((item) => item.row));
  const defaultId = rows.length ? chooseDefault(rows, preferredDefault) : '';
  if (!rows.length) errors.push('No design passed review; the library would be empty.');
  const index: DesignIndex = { version: TOKENS_VERSION, default: defaultId, designs: rows };
  const review: DesignReview = {
    version: TOKENS_VERSION,
    excluded: sortByName(excluded),
    notes: sortByName(notes),
  };

  return {
    index,
    review,
    tokens: shipped.map((item) => ({ id: item.tokens.id, text: renderJson(item.tokens) })).sort((a, b) => (a.id < b.id ? -1 : 1)),
    library: renderLibrary(index, shipped.map((item) => item.tokens)),
    errors,
    proposals,
  };
}
