/**
 * The recipe pipeline (parai §5) as one pure function: JSON files in, validated recipes and
 * the generated import map out. Nothing here touches the filesystem so the same code runs in
 * the digest script and in the drift test.
 *
 * Fatal errors are limited to a broken library: two recipes with the same name, or none at
 * all. Anything else excludes that one recipe and reports why.
 */

import { renderJson } from '../designs/build.ts';
import { checkRecipe } from './schema.ts';
import { recipeEligible, type SlotFacts } from './slots.ts';
import type { Recipe } from './recipe.ts';

export interface RecipeSourceFile {
  file: string;
  text: string;
}

export interface RecipeBuild {
  /** Keyed `type/id`, sorted by key so the generated file is byte-stable. */
  recipes: { key: string; recipe: Recipe }[];
  /** A recipe that is well-formed but cannot be filled from the sample profile. */
  unfillable: { file: string; missing: string[] }[];
  excluded: { file: string; problems: string[] }[];
  library: string;
  errors: string[];
}

function parseSource(source: RecipeSourceFile): { recipe?: unknown; problems: string[] } {
  try {
    return { recipe: JSON.parse(source.text), problems: [] };
  } catch (error) {
    return { problems: [`Recipe JSON does not parse: ${String(error)}`] };
  }
}

export function buildRecipes(sources: RecipeSourceFile[], facts: SlotFacts): RecipeBuild {
  const errors: string[] = [];
  const excluded: { file: string; problems: string[] }[] = [];
  const unfillable: { file: string; missing: string[] }[] = [];
  const byKey = new Map<string, Recipe>();

  for (const source of [...sources].sort((a, b) => (a.file < b.file ? -1 : a.file > b.file ? 1 : 0))) {
    const parsed = parseSource(source);
    if (parsed.problems.length) {
      excluded.push({ file: source.file, problems: parsed.problems });
      continue;
    }
    const checked = checkRecipe(parsed.recipe, source.file);
    if (!checked.recipe) {
      excluded.push({ file: source.file, problems: checked.problems });
      continue;
    }
    const recipe = checked.recipe;
    const key = `${recipe.type}/${recipe.id}`;
    if (byKey.has(key)) {
      errors.push(`Two recipes claim ${key}; ${source.file} is the second.`);
      continue;
    }
    const eligibility = recipeEligible(recipe, facts);
    if (!eligibility.ok) {
      unfillable.push({ file: source.file, missing: eligibility.missing });
      continue;
    }
    byKey.set(key, recipe);
  }

  const recipes = [...byKey.entries()]
    .sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0))
    .map(([key, recipe]) => ({ key, recipe }));

  if (!recipes.length) errors.push('No recipe survived checking; the renderer would have nothing to choose from.');

  return { recipes, unfillable, excluded, library: renderLibrary(recipes), errors };
}

function renderLibrary(recipes: { key: string; recipe: Recipe }[]): string {
  const map: Record<string, Recipe> = {};
  for (const entry of recipes) map[entry.key] = entry.recipe;
  return `/**
 * Generated by \`npm run recipes\` from src/site/recipes/<type>/<id>.json. Do not edit:
 * the digest rewrites this file and a test fails if the committed copy differs.
 */

import type { Recipe } from './recipe.ts';

export const GENERATED_RECIPES: Record<string, Recipe> = ${renderJson(map).trimEnd()};
`;
}
